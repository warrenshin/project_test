def _resolve_lesson_id(conn, code: str):
    row = conn.execute(sa.text("SELECT id FROM lessons WHERE code = :code"), {"code": code}).first()
    if row is None:
        raise RuntimeError(f"lesson code {code!r}를 찾을 수 없습니다 — 이전 migration이 먼저 적용돼야 합니다.")
    return row[0]


def _resolve_quiz_id(conn, lesson_id):
    row = conn.execute(sa.text("SELECT id FROM quizzes WHERE lesson_id = :lesson_id"), {"lesson_id": lesson_id}).first()
    if row is None:
        raise RuntimeError(f"lesson_id {lesson_id}의 quiz를 찾을 수 없습니다.")
    return row[0]


def _resolve_question_id(conn, quiz_id, order_index: int):
    row = conn.execute(
        sa.text("SELECT id FROM questions WHERE quiz_id = :quiz_id AND order_index = :oi"),
        {"quiz_id": quiz_id, "oi": order_index},
    ).first()
    if row is None:
        raise RuntimeError(f"quiz_id {quiz_id}의 order_index={order_index} 문항을 찾을 수 없습니다.")
    return row[0]


def _resolve_choice_id(conn, question_id, order_index: int):
    row = conn.execute(
        sa.text("SELECT id FROM choices WHERE question_id = :question_id AND order_index = :oi"),
        {"question_id": question_id, "oi": order_index},
    ).first()
    if row is None:
        raise RuntimeError(f"question_id {question_id}의 order_index={order_index} 선택지를 찾을 수 없습니다.")
    return row[0]


def _verified_update(conn, table, id_value, field: str, expected_current, new_value) -> None:
    row = conn.execute(sa.text(f"SELECT {field} FROM {table} WHERE id = :id"), {"id": id_value}).first()
    current = row[0] if row else None
    if current != expected_current:
        raise RuntimeError(
            f"{table}.id={id_value}의 {field} 현재 값이 예상과 다릅니다 — 다른 경로로 이미 바뀐 것으로 "
            f"보입니다. 예상: {expected_current!r}, 실제: {current!r}. 수동으로 확인해주세요."
        )
    conn.execute(sa.text(f"UPDATE {table} SET {field} = :new WHERE id = :id"), {"new": new_value, "id": id_value})


def _apply(conn, direction: str) -> None:
    assert direction in ("upgrade", "downgrade")
    from_key, to_key = ("old", "new") if direction == "upgrade" else ("new", "old")

    for code, correction in CORRECTIONS.items():
        lesson_id = _resolve_lesson_id(conn, code)
        market_scope = correction["market_scope"]

        source = correction.get("source")
        if source is not None:
            _verified_update(conn, "lessons", lesson_id, "source", source[f"{from_key}_title"], source[f"{to_key}_title"])
            _verified_update(conn, "lessons", lesson_id, "source_url", source[f"{from_key}_url"], source[f"{to_key}_url"])

        blocks = correction.get("blocks", {})
        for block_type, patch in blocks.items():
            cb_row = conn.execute(
                sa.text("SELECT id FROM content_blocks WHERE lesson_id = :lid AND block_type = :bt"),
                {"lid": lesson_id, "bt": block_type},
            ).first()
            if cb_row is None:
                raise RuntimeError(f"{code}의 {block_type} content_block을 찾을 수 없습니다.")
            cb_id = cb_row[0]

            old_value, new_value = patch["old"], patch["new"]
            if block_type == "TERMS":
                old_text, new_text = _join_terms(old_value), _join_terms(new_value)
            elif block_type in ("MISCONCEPTION", "SUMMARY"):
                old_text, new_text = _join_bullets(old_value), _join_bullets(new_value)
            elif block_type == "BODY":
                old_text, new_text = _join_body(old_value), _join_body(new_value)
            else:
                old_text, new_text = old_value, new_value  # EXAMPLE, PRACTICE: 단일 문자열

            expected, target = (old_text, new_text) if direction == "upgrade" else (new_text, old_text)
            _verified_update(conn, "content_blocks", cb_id, "content", expected, target)

        # SOURCE 블록은 source_title/source_url이 바뀌면 항상 같이 재생성한다(별도 patch 불필요).
        if source is not None:
            old_source_note = _source_note(source["old_title"], source["old_url"], market_scope)
            new_source_note = _source_note(source["new_title"], source["new_url"], market_scope)
            source_cb_row = conn.execute(
                sa.text("SELECT id FROM content_blocks WHERE lesson_id = :lid AND block_type = 'SOURCE'"),
                {"lid": lesson_id},
            ).first()
            if source_cb_row is None:
                raise RuntimeError(f"{code}의 SOURCE content_block을 찾을 수 없습니다.")
            expected, target = (
                (old_source_note, new_source_note) if direction == "upgrade" else (new_source_note, old_source_note)
            )
            _verified_update(conn, "content_blocks", source_cb_row[0], "content", expected, target)

        questions = correction.get("questions", {})
        if questions:
            quiz_id = _resolve_quiz_id(conn, lesson_id)
        for q_order, q_patch in questions.items():
            question_id = _resolve_question_id(conn, quiz_id, q_order)
            if "old_prompt" in q_patch:
                expected, target = (
                    (q_patch["old_prompt"], q_patch["new_prompt"])
                    if direction == "upgrade"
                    else (q_patch["new_prompt"], q_patch["old_prompt"])
                )
                _verified_update(conn, "questions", question_id, "prompt", expected, target)
            if "old_explanation" in q_patch:
                expected, target = (
                    (q_patch["old_explanation"], q_patch["new_explanation"])
                    if direction == "upgrade"
                    else (q_patch["new_explanation"], q_patch["old_explanation"])
                )
                _verified_update(conn, "questions", question_id, "explanation", expected, target)

            for c_order, c_patch in q_patch.get("choices", {}).items():
                choice_id = _resolve_choice_id(conn, question_id, c_order)
                if "old_label" in c_patch:
                    expected, target = (
                        (c_patch["old_label"], c_patch["new_label"])
                        if direction == "upgrade"
                        else (c_patch["new_label"], c_patch["old_label"])
                    )
                    _verified_update(conn, "choices", choice_id, "label", expected, target)
                if "old_explanation" in c_patch:
                    expected, target = (
                        (c_patch["old_explanation"], c_patch["new_explanation"])
                        if direction == "upgrade"
                        else (c_patch["new_explanation"], c_patch["old_explanation"])
                    )
                    _verified_update(conn, "choices", choice_id, "explanation", expected, target)


def upgrade() -> None:
    conn = op.get_bind()
    _apply(conn, "upgrade")


def downgrade() -> None:
    conn = op.get_bind()
    _apply(conn, "downgrade")
